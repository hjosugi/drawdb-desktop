// Shared DDL generation skeleton for the desktop SQL exporters.
//
// A dialect is a plain object describing only what differs between databases
// (quoting, type mapping, column clause order, where comments and indexes go,
// foreign-key action support, surrounding statements). `generateDdl` owns the
// statement order: header, composite types, enum types, tables (with their
// comments and indexes), foreign keys, trailer. See docs/sql-dialects.md.
import { findField } from "./common.js";

/** @typedef {{ sql: string, checks?: string[], serial?: boolean }} ColumnDefinition */

export const quoteWith = (open, close = open) => (value) =>
  `${open}${String(value).split(close).join(close + close)}${close}`;

export const sqlStringLiteral = (value) => `'${String(value).replace(/'/g, "''")}'`;

export const hasDefault = (field) => field.default !== "" && field.default != null;

export const upperType = (field, fallback) => String(field.type || fallback).toUpperCase();

/** Maps lower-cased enum names to their definitions (first one wins). */
export function namedEnumMap(diagram) {
  const enums = new Map();
  (diagram.enums || []).forEach((definition) => {
    if (!definition?.name) return;
    const key = String(definition.name).toLowerCase();
    if (!enums.has(key)) enums.set(key, definition);
  });
  return enums;
}

/**
 * Values of an enumerated column: inline `ENUM` values, or the values of a
 * named enum referenced as the column type. Returns null otherwise.
 */
export function enumValues(field, context) {
  const type = String(field.type || "");
  if (type.toUpperCase() === "ENUM") {
    return Array.isArray(field.values) && field.values.length ? field.values : null;
  }
  const named = context?.namedEnums?.get(type.toLowerCase());
  return Array.isArray(named?.values) && named.values.length ? named.values : null;
}

/** Resolves a relationship to table/column names, or null when dangling. */
export function resolveRelationship(diagram, relationship) {
  const tables = diagram.tables || [];
  const source = tables.find((table) => table.id === relationship.startTableId);
  const target = tables.find((table) => table.id === relationship.endTableId);
  if (!source || !target) return null;
  const sourceColumn = findField(source, relationship.startFieldId)?.name;
  const targetColumn = findField(target, relationship.endFieldId)?.name;
  if (!sourceColumn || !targetColumn) return null;
  return { source, target, sourceColumn, targetColumn };
}

const normalizeAction = (action) => String(action || "").toUpperCase();

/**
 * Referential action clauses. `onDelete` / `onUpdate` list the actions the
 * dialect accepts (`"all"` = anything except NO ACTION, which is the default).
 */
export function referentialActions(relationship, { onDelete = "all", onUpdate = "all" } = {}) {
  const emit = (keyword, action, allowed) => {
    if (!action || action === "NO ACTION" || !allowed) return "";
    if (allowed !== "all" && !allowed.includes(action)) return "";
    return ` ${keyword} ${action}`;
  };
  return (
    emit("ON DELETE", normalizeAction(relationship.deleteConstraint), onDelete)
    + emit("ON UPDATE", normalizeAction(relationship.updateConstraint), onUpdate)
  );
}

function headerLines(diagram, dialect) {
  return [
    `-- Generated by drawDB Desktop (${dialect.label})`,
    "-- Diagram: " + (diagram.name || ""),
    "-- Generated: " + new Date().toISOString(),
  ];
}

function tableStatements(table, dialect, context) {
  const q = dialect.quoteIdent;
  const fields = table.fields || [];
  const lines = [];
  const checks = [];

  for (const field of fields) {
    const column = dialect.column(field, table, context);
    lines.push(`  ${q(field.name)} ${column.sql}`);
    checks.push(...(column.checks || []));
  }

  const primaryColumns = fields.filter((field) => field.primary).map((field) => q(field.name));
  if (primaryColumns.length) lines.push(`  ${dialect.primaryKey(table, primaryColumns)}`);
  checks.forEach((check) => lines.push(`  ${check}`));

  const indexes = table.indices || [];
  const indexColumns = (index) => (index.fields || []).map(q).join(", ");
  if (dialect.indexes === "inline") {
    indexes.forEach((index) => {
      lines.push(`  ${index.unique ? "UNIQUE " : ""}KEY ${q(index.name)} (${indexColumns(index)})`);
    });
  }

  const suffix = dialect.tableSuffix?.(table) ?? "";
  const statements = [`CREATE TABLE ${q(table.name)} (\n${lines.join(",\n")}\n)${suffix};`];

  if (dialect.comments === "statements") {
    statements.push(...dialect.commentStatements(table));
  }
  if (dialect.indexes === "statements") {
    indexes.forEach((index) => {
      statements.push(
        `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${q(index.name)} ON ${q(table.name)} (${indexColumns(index)});`,
      );
    });
  }
  return statements;
}

function foreignKeyStatement(diagram, relationship, index, dialect) {
  const resolved = resolveRelationship(diagram, relationship);
  if (!resolved) return null;
  const q = dialect.quoteIdent;
  const { source, target, sourceColumn, targetColumn } = resolved;
  const name = relationship.name || dialect.foreignKeyName(source, target, index);
  return `ALTER TABLE ${q(source.name)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${q(sourceColumn)}) REFERENCES ${q(target.name)} (${q(targetColumn)})`
    + referentialActions(relationship, dialect.foreignKeyActions)
    + ";";
}

/**
 * Generates a DDL script for `diagram` using `dialect`.
 * @param {object} diagram drawDB diagram (tables, relationships, types, enums)
 * @param {object} dialect dialect definition
 */
export function generateDdl(diagram, dialect) {
  const context = { diagram, namedEnums: namedEnumMap(diagram) };
  const parts = [...headerLines(diagram, dialect), ...(dialect.preamble || [""])];

  if (dialect.compositeType) {
    (diagram.types || []).forEach((type) => parts.push(dialect.compositeType(type, context)));
  }
  parts.push(...(dialect.typeDefinitions?.(diagram, context) || []));

  (diagram.tables || []).forEach((table) => {
    parts.push(...tableStatements(table, dialect, context));
    parts.push("");
  });

  (diagram.relationships || []).forEach((relationship, index) => {
    const statement = foreignKeyStatement(diagram, relationship, index, dialect);
    if (statement) parts.push(statement);
  });

  parts.push(...(dialect.trailer || []));
  return parts.join("\n");
}

/** COMMENT ON TABLE / COLUMN statements shared by Oracle and PostgreSQL. */
export function commentOnStatements(quoteIdent, quoteLiteral = sqlStringLiteral) {
  return (table) => {
    const statements = [];
    if (table.comment) {
      statements.push(`COMMENT ON TABLE ${quoteIdent(table.name)} IS ${quoteLiteral(table.comment)};`);
    }
    (table.fields || []).forEach((field) => {
      if (field.comment) {
        statements.push(
          `COMMENT ON COLUMN ${quoteIdent(table.name)}.${quoteIdent(field.name)} IS ${quoteLiteral(field.comment)};`,
        );
      }
    });
    return statements;
  };
}
