// @ts-check
// Oracle SQL exporter for drawDB (dialect definition for core.js)
import {
  commentOnStatements,
  enumValues,
  generateDdl,
  hasDefault,
  quoteWith,
  sqlStringLiteral,
  upperType,
} from "./core.js";

const SAFE = quoteWith('"');
const SAFE_LIT = sqlStringLiteral;

const TYPE_MAP = {
  INT: "NUMBER(10)", INTEGER: "NUMBER(10)", BIGINT: "NUMBER(19)",
  SMALLINT: "NUMBER(5)", TINYINT: "NUMBER(3)",
  DECIMAL: null, NUMERIC: null, NUMBER: null, FLOAT: "BINARY_FLOAT", DOUBLE: "BINARY_DOUBLE", REAL: "BINARY_FLOAT",
  VARCHAR: "VARCHAR2", VARCHAR2: "VARCHAR2", CHAR: "CHAR", TEXT: "CLOB", LONGTEXT: "CLOB", MEDIUMTEXT: "CLOB", TINYTEXT: "VARCHAR2(255)",
  BLOB: "BLOB", LONGBLOB: "BLOB", MEDIUMBLOB: "BLOB", TINYBLOB: "RAW(255)", BINARY: "RAW", VARBINARY: "RAW",
  DATE: "DATE", TIME: "TIMESTAMP", DATETIME: "TIMESTAMP", TIMESTAMP: "TIMESTAMP",
  BOOLEAN: "NUMBER(1)", BOOL: "NUMBER(1)", BIT: "NUMBER(1)",
  JSON: "CLOB", UUID: "VARCHAR2(36)", ENUM: "VARCHAR2(255)",
};

function mapType(f, context) {
  const upper = upperType(f, "VARCHAR2");
  const mapped = TYPE_MAP[upper];
  const values = enumValues(f, context);
  if (values) {
    return { type: `VARCHAR2(${Math.max(10, ...values.map(v => String(v).length))})`,
             check: `${SAFE(f.name)} IN (${values.map(SAFE_LIT).join(",")})` };
  }
  if (mapped === null) {
    const s = String(f.size || "10,0");
    return { type: `NUMBER(${s})` };
  }
  if (mapped) {
    if (mapped === "VARCHAR2" || mapped === "CHAR") {
      const sz = Number(f.size) || 255;
      return { type: `${mapped}(${Math.min(4000, sz)})` };
    }
    if (mapped === "RAW") return { type: `RAW(${Number(f.size) || 2000})` };
    return { type: mapped };
  }
  return { type: upper };
}

function formatDefault(f) {
  const v = String(f.default);
  if (/^(CURRENT_TIMESTAMP|now\(\)|SYSDATE|SYSTIMESTAMP)$/i.test(v)) {
    return /^SYS/i.test(v) ? v.toUpperCase() : "CURRENT_TIMESTAMP";
  }
  if (/^-?\d+(\.\d+)?$/.test(v)) return v;
  if (/^(true|false)$/i.test(v)) return v.toLowerCase() === "true" ? "1" : "0";
  if (v.toUpperCase() === "NULL") return "NULL";
  return SAFE_LIT(v);
}

export const oracleDialect = Object.freeze({
  id: "oracle",
  label: "Oracle dialect",
  quoteIdent: SAFE,
  quoteLiteral: SAFE_LIT,
  compositeType: (t, context) => {
    const cols = (t.fields || []).map((f) => `  ${SAFE(f.name)} ${mapType(f, context).type}`).join(",\n");
    return `CREATE OR REPLACE TYPE ${SAFE(t.name)} AS OBJECT (\n${cols}\n);\n/`;
  },
  column(f, t, context) {
    const m = mapType(f, context);
    const checks = [];
    let sql = m.type;
    // Oracle grammar: datatype [DEFAULT expr | identity_clause] [constraints].
    if (f.increment) sql += " GENERATED BY DEFAULT AS IDENTITY";
    else if (hasDefault(f)) sql += ` DEFAULT ${formatDefault(f)}`;
    if (f.notNull) sql += " NOT NULL";
    if (f.unique && !f.primary) sql += " UNIQUE";
    if (f.check) checks.push(`CONSTRAINT ${SAFE("chk_" + t.name + "_" + f.name)} CHECK (${f.check})`);
    if (m.check) checks.push(`CONSTRAINT ${SAFE("chk_" + t.name + "_" + f.name + "_enum")} CHECK (${m.check})`);
    return { sql, checks };
  },
  primaryKey: (t, columns) => `CONSTRAINT ${SAFE("pk_" + t.name)} PRIMARY KEY (${columns.join(", ")})`,
  indexes: "statements",
  comments: "statements",
  commentStatements: commentOnStatements(SAFE, SAFE_LIT),
  // Oracle identifiers were limited to 30 bytes before 12.2.
  foreignKeyName: (source, target, index) => `fk_${source.name}_${target.name}_${index + 1}`.slice(0, 30),
  // Oracle supports ON DELETE CASCADE / SET NULL only, and no ON UPDATE.
  foreignKeyActions: { onDelete: ["CASCADE", "SET NULL"], onUpdate: [] },
  trailer: [],
});

/**
 * @param {import("../../types/drawdb").Diagram} diagram
 * @returns {string} DDL script
 */
export function toOracle(diagram) {
  return generateDdl(diagram, oracleDialect);
}
